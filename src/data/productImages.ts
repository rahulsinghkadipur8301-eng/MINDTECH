export function getProductSpecificImage(id: string): string {
  if (PRODUCT_SPECIFIC_IMAGES[id]) {
    return PRODUCT_SPECIFIC_IMAGES[id];
  }

  // Dynamic deterministic routing based on product prefix
  if (id.startsWith('sns-')) {
    return `/products/sns/${id}.svg`;
  }
  if (id.startsWith('vegarol-') || id.startsWith('promisoft-')) {
    return `/products/vvf/${id}.svg`;
  }
  if (id.startsWith('finagreen-') || id.startsWith('finamide-') || id.startsWith('vbrass-') || id.startsWith('finester-')) {
    return `/products/fine-organics/${id}.svg`;
  }

  // Local Greentech or universal verified fallback
  return '/products/greentech/timelys.png';
}
